import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { basename, dirname, join, resolve } from "node:path";
import { defineCommand, flag } from "@prisma/cli-engine";
import { CliStructuredError, notOk, ok } from "@prisma/cli-engine/protocol";
import { executeContractEmit } from "@prisma/orm-toolchain/cli/control-api";
import { createCollectingSink, presentationsFromSink } from "./collecting-sink";
import { ormConfigSection } from "./config-section";

// Match upstream's per-output serialization, including our third artifact.
const publications = new Map<string, Promise<unknown>>();

async function serializePublication<T>(output: string, action: () => Promise<T>): Promise<T> {
  const previous = publications.get(output) ?? Promise.resolve();
  const current = previous.catch(() => {}).then(action);
  publications.set(output, current);
  try {
    return await current;
  } finally {
    if (publications.get(output) === current) publications.delete(output);
  }
}

async function readPrevious(path: string): Promise<Buffer | undefined> {
  try {
    return await readFile(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw error;
  }
}

/** Publish declarations and module before JSON, restoring the previous set on failure. */
async function publishArtifacts(stage: string, paths: readonly string[]): Promise<void> {
  // Read all previous artifacts before replacing any, so a read failure changes nothing.
  const previous = await Promise.all(paths.map(readPrevious));
  let replaced = 0;
  try {
    for (const path of paths) {
      await rename(join(stage, basename(path)), path);
      replaced++;
    }
  } catch (error) {
    const failures: unknown[] = [];
    for (let index = replaced - 1; index >= 0; index--) {
      const path = paths[index]!;
      try {
        const bytes = previous[index];
        if (bytes === undefined) {
          await rm(path, { force: true });
        } else {
          const restore = join(stage, `${index}.restore`);
          await writeFile(restore, bytes);
          await rename(restore, path);
        }
      } catch (failure) {
        failures.push(failure);
      }
    }
    if (failures.length > 0) {
      throw new AggregateError([error, ...failures], "Contract publication failed and could not be restored");
    }
    throw error;
  }
}

/** Family-agnostic wrapper: upstream owns resolution, validation, hashing and declaration emission. */
export const contractEmitCommand = defineCommand({
  needs: { config: ormConfigSection },
  help: {
    summary: "Emit contract JSON, declarations, and a typed runtime module",
    description: "Emits IDB or SQL contracts with a default export in <name>.runtime.ts.",
    examples: ["contract emit", "contract emit --config prisma.config.postgres.ts"],
  },
  args: {
    flags: {
      output: flag.string({ brief: "Output directory (default: orm.contract.output)", placeholder: "directory" }),
    },
  },
  handler: async (args, ctx) => {
    try {
      const output =
        args.flags.output === undefined
          ? ctx.config.contract?.output
          : resolve(ctx.cwd, args.flags.output, "contract.json");
      if (!output?.endsWith(".json")) {
        throw new CliStructuredError("IDB-CLI.CONTRACT_OUTPUT", "contract.output must name a .json file.");
      }
      const jsonPath = resolve(ctx.cwd, output);
      const stem = basename(jsonPath, ".json");
      const dtsPath = join(dirname(jsonPath), `${stem}.d.ts`);
      const modulePath = join(dirname(jsonPath), `${stem}.runtime.ts`);
      const result = await serializePublication(jsonPath, async () => {
        await mkdir(dirname(jsonPath), { recursive: true });
        const stage = await mkdtemp(join(dirname(jsonPath), ".contract-emit-"));
        try {
          const emitted = await executeContractEmit({
            config: { ...ctx.config, contract: { ...ctx.config.contract!, output: join(stage, basename(jsonPath)) } },
            cwd: ctx.cwd,
            // Preserve the consumer's package resolution while upstream writes into staging.
            projectDir: ctx.config.baseDir ?? ctx.cwd,
            signal: ctx.signal,
          });
          const source = [
            "// Generated by prisma-idb contract emit. Do not edit.",
            `import json from ${JSON.stringify(`./${basename(jsonPath)}`)} with { type: "json" };`,
            `import type { Contract } from ${JSON.stringify(`./${stem}.d`)};`,
            `export type * from ${JSON.stringify(`./${stem}.d`)};`,
            "// The upstream emitter validates these bytes and produces the matching branded types.",
            "const contract = json as unknown as Contract;",
            "export default contract;",
            "",
          ].join("\n");
          await writeFile(join(stage, basename(modulePath)), source);
          ctx.signal.throwIfAborted();
          await publishArtifacts(stage, [dtsPath, modulePath, jsonPath]);
          return { ...emitted, files: { json: jsonPath, dts: dtsPath, module: modulePath } };
        } finally {
          await rm(stage, { recursive: true, force: true });
        }
      });
      const warnings = [result.validationWarning, ...(result.sourceWarnings?.map((warning) => warning.message) ?? [])]
        .filter(Boolean)
        .join("\n");
      const sink = createCollectingSink();
      sink.out(`Emitted ${basename(jsonPath)}, ${basename(dtsPath)}, and ${basename(modulePath)}\n`);
      if (warnings) sink.err(warnings);
      return ok(ctx.present({ data: result }, { ...presentationsFromSink(sink, 0), json: () => result }));
    } catch (error) {
      return notOk(
        CliStructuredError.is(error)
          ? error
          : new CliStructuredError(
              "IDB-CLI.CONTRACT_EMIT_FAILED",
              error instanceof Error ? error.message : String(error)
            )
      );
    }
  },
});
